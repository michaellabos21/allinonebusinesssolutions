import { computeInvoiceTotals, lineTotalMinor } from "@/lib/money";

import type { Invoice, Payment } from "./types";

type Line = [description: string, quantity: number, unitPriceMinor: number];

/** Builds a demo invoice; the total is computed from its lines, never typed. */
const invoice = (
  id: string,
  number: string,
  contactId: string,
  description: string,
  status: "draft" | "sent" | "paid",
  issuedOn: string,
  dueOn: string,
  paidOn: string | null,
  lines: Line[],
): Invoice => {
  const items = lines.map(([lineDescription, quantity, unitPriceMinor], index) => ({
    id: `${id}-${index + 1}`,
    description: lineDescription,
    quantityMilli: quantity * 1000,
    unitPriceMinor,
    amountMinor: lineTotalMinor({ quantityMilli: quantity * 1000, unitPriceMinor }),
    catalogItemId: null,
  }));
  const totals = computeInvoiceTotals(items);
  return {
    id,
    number: status === "draft" ? null : number,
    contactId,
    billTo: null,
    description,
    items,
    discountMinor: 0,
    taxRateBps: 0,
    notes: "",
    subtotalMinor: totals.subtotalMinor,
    taxMinor: totals.taxMinor,
    amountMinor: totals.totalMinor,
    paidMinor: status === "paid" ? totals.totalMinor : 0,
    currency: "PHP",
    status,
    issuedOn,
    dueOn,
    paidOn,
    voidReason: "",
    estimateId: null,
  };
};

